-- V4 — INTICS-side adoption tracking.
--
-- model_adoptions holds the CURRENT internal state of a model (stage, owner, team,
-- use case). A model only gets a row once somebody marks it, so "no row" means
-- NOT_REVIEWED. adoption_events is the append-only timeline of every save.

CREATE TABLE model_adoptions (
    model_id          VARCHAR(255) PRIMARY KEY
                          REFERENCES tracked_models (id) ON DELETE CASCADE,
    status            VARCHAR(255) NOT NULL,              -- EVALUATING | IN_PROGRESS | DEPLOYED | ON_HOLD | REJECTED
    owner             VARCHAR(255),                       -- person deploying / working with it
    team              VARCHAR(255),
    use_case          TEXT,
    notes             TEXT,
    first_marked_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    status_changed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_model_adoptions_status ON model_adoptions (status);
CREATE INDEX idx_model_adoptions_owner ON model_adoptions (owner);

CREATE TABLE adoption_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id    VARCHAR(255) NOT NULL
                    REFERENCES tracked_models (id) ON DELETE CASCADE,
    from_status VARCHAR(255),                             -- null on the first entry
    to_status   VARCHAR(255) NOT NULL,
    owner       VARCHAR(255),
    team        VARCHAR(255),
    use_case    TEXT,
    note        TEXT,
    changed_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_adoption_events_model ON adoption_events (model_id, changed_at DESC);
