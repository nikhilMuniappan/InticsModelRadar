-- V3 — audit trail of sync runs (Section 10 #1).
-- One row per run: what triggered it, whether it succeeded, timings, and counts.
-- Read by GET /api/health to confirm a recent successful sync.

CREATE TABLE sync_runs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trigger_source VARCHAR(255) NOT NULL,                 -- SCHEDULED | MANUAL
    status         VARCHAR(255) NOT NULL,                 -- RUNNING | SUCCESS | FAILURE
    started_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    finished_at    TIMESTAMP(6) WITH TIME ZONE,
    models_checked INTEGER,
    new_count      INTEGER,
    updated_count  INTEGER,
    error_message  TEXT
);
